using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Options;
using Random.User.Rest.Infrastructure;
using Random.User.Rest.Model;

namespace Random.User.Rest.Controllers;

[ApiController]
[Route("api/user")]
public sealed class UsersController(DataContext context, IOptions<ConfigurationOptions> options) : ControllerBase
{
    // Pages are one-based. `cant` is retained for compatibility with the original API.
    [HttpGet]
    public async Task<ActionResult<IEnumerable<Model.User>>> GetUsers(
        [FromQuery] int page = 1, [FromQuery] int? cant = null, CancellationToken cancellationToken = default)
    {
        if (page < 1 || cant is <= 0) return BadRequest("page and cant must be positive.");

        var size = Math.Min(cant ?? options.Value.MaxUsersLimit, options.Value.MaxUsersLimit);
        var skip = ((long)page - 1) * size;
        if (skip > int.MaxValue) return BadRequest("Requested page is too large.");

        var users = await context.Users.AsNoTracking().Include(user => user.Location)
            .OrderBy(user => user.Name).ThenBy(user => user.UserId)
            .Skip((int)skip).Take(size).ToListAsync(cancellationToken);

        var eldest = users.OrderByDescending(user => user.Age).ThenBy(user => user.UserId).FirstOrDefault();
        if (eldest is not null) eldest.IsTheEldest = true;
        return Ok(users);
    }

    [HttpGet("{id:int}")]
    public async Task<ActionResult<Model.User>> GetUser(int id, CancellationToken cancellationToken)
    {
        var user = await context.Users.AsNoTracking().Include(u => u.Location)
            .FirstOrDefaultAsync(u => u.UserId == id, cancellationToken);
        return user is null ? NotFound() : Ok(user);
    }

    [HttpPost]
    public async Task<ActionResult<Model.User>> PostUser(Model.User user, CancellationToken cancellationToken)
    {
        // IDs are generated by the store; never trust relationship IDs from clients.
        user.UserId = 0;
        if (user.Location is not null) { user.Location.LocationId = 0; user.Location.UserId = 0; }
        user.IsTheEldest = false;
        context.Users.Add(user);
        await context.SaveChangesAsync(cancellationToken);
        return CreatedAtAction(nameof(GetUser), new { id = user.UserId }, user);
    }

    [HttpPut("{id:int}")]
    public async Task<IActionResult> PutUser(int id, Model.User update, CancellationToken cancellationToken)
    {
        if (id != update.UserId) return BadRequest("Route and body user IDs must match.");
        var user = await context.Users.Include(u => u.Location)
            .FirstOrDefaultAsync(u => u.UserId == id, cancellationToken);
        if (user is null) return NotFound();

        user.Gender = update.Gender;
        user.Name = update.Name;
        user.Email = update.Email;
        user.BirthDate = update.BirthDate;
        user.Uuid = update.Uuid;
        user.UserName = update.UserName;
        user.Age = update.Age;
        if (update.Location is null)
        {
            if (user.Location is not null) context.Locations.Remove(user.Location);
        }
        else if (user.Location is null)
        {
            user.Location = new Model.Location();
            CopyLocation(update.Location, user.Location);
        }
        else CopyLocation(update.Location, user.Location);

        await context.SaveChangesAsync(cancellationToken);
        return NoContent();
    }

    [HttpDelete("{id:int}")]
    public async Task<IActionResult> DeleteUser(int id, CancellationToken cancellationToken)
    {
        var user = await context.Users.FindAsync([id], cancellationToken);
        if (user is null) return NotFound();
        context.Users.Remove(user);
        await context.SaveChangesAsync(cancellationToken);
        return NoContent();
    }

    private static void CopyLocation(Model.Location source, Model.Location target)
    {
        target.Street = source.Street;
        target.City = source.City;
        target.State = source.State;
        target.PostCode = source.PostCode;
    }
}
